inline float textWidth(const std::string& s, float scale)
{
    return s.empty() ? 0.f : (s.size() * 6 - 1) * scale;
}

/// Draws `s` with its lower-left corner at `pos`.  `colorOf(i)` may vary the colour per character.
inline void draw(ax::DrawNode* dn,
                 const std::string& s,
                 ax::Vec2 pos,
                 float scale,
                 const std::function<ax::Color(size_t)>& colorOf)
{
    float x = pos.x;
    for (size_t i = 0; i < s.size(); ++i, x += 6 * scale)
    {
        char c = s[i];
        if (c != 'x')
            c = (char)std::toupper((unsigned char)c);
        auto g = find(c);
        if (!g)
            continue;
        auto col = colorOf(i);
        for (int r = 0; r < 7; ++r)
        {
            const char* row = g->rows[r];
            float y         = pos.y + (6 - r) * scale;
            for (int cI = 0; cI < 5;)
            {
                if (row[cI] != '#')
                {
                    ++cI;
                    continue;
                }
                int run = cI;
                while (run < 5 && row[run] == '#')
                    ++run;
                dn->drawSolidRect(ax::Vec2(x + cI * scale, y), ax::Vec2(x + run * scale, y + scale), col);
                cI = run;
            }
        }
    }
}

inline void draw(ax::DrawNode* dn, const std::string& s, ax::Vec2 pos, float scale, ax::Color col)
{
    draw(dn, s, pos, scale, [col](size_t) { return col; });
}

/// Text with a dark drop shadow, anchored: ax=0 left, 0.5 centre, 1 right.
inline void drawShadow(ax::DrawNode* dn, const std::string& s, ax::Vec2 pos, float scale, ax::Color col,
                       float anchorX = 0.f)
{
    pos.x -= textWidth(s, scale) * anchorX;
    draw(dn, s, pos + ax::Vec2(scale, -scale), scale, ax::Color(0.f, 0.f, 0.f, 0.8f));
    draw(dn, s, pos, scale, col);
}
