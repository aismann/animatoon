#!/usr/bin/env python3
"""
Extracts the embedded data of the PureBasic "Snowball" (Majikeyric, PurePunch
XMas 2014) and writes the assets used by the Axmol port:

  Source/GameData.cpp   palette, C64 sprites, C64 charset + colour attributes,
                        tile map and animation tables (5296 bytes)
  Content/music.ogg     the embedded MIDI file, rendered with a tiny
                        synthesizer (Axmol's AudioEngine cannot play MIDI)

Usage:  python3 tools/extract_assets.py [original/snowball.pb]
Needs:  numpy and ffmpeg (for the OGG encode; a WAV is written if missing)
"""
import re, struct, lzma, sys, os, subprocess, wave
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "original", "snowball.pb")

PACKED, UNPACKED, MIDI_SIZE = 2920, 13431, 8135        # #P, #U, #SS of the .pb

# ---- 1. hex data -> LZMA stream -> raw data --------------------------------
text = open(src_path, "rb").read().decode("latin1")
text = text[text.index(".s\"5D00"):]
raw = bytes.fromhex("".join(re.findall(r'"([0-9A-F]*)"', text)))[:PACKED]
# PureBasic's LZMA packer omits the 8 byte "uncompressed size" of the .lzma header
data = lzma.decompress(raw[:5] + struct.pack("<Q", UNPACKED) + raw[5:], format=lzma.FORMAT_ALONE)
assert len(data) == UNPACKED

# layout: palette | 13 sprites | 256 chars | 256 char colours | map | midi | anims
SIZES = [("palette", 64), ("sprites", 13 * 64), ("chars", 256 * 8), ("charColors", 256),
         ("map", 25 * 80), ("midi", MIDI_SIZE), ("anims", 6 * 16)]
parts, o = {}, 0
for name, n in SIZES:
    parts[name] = data[o:o + n]; o += n
assert o == UNPACKED

# ---- 2. Source/GameData.cpp ---------------------------------------------------
def carray(name, b):
    rows = [", ".join("0x%02X" % x for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return "const uint8_t %s[%d] = {\n    %s};\n" % (name, len(b), ",\n    ".join(rows))

with open(os.path.join(ROOT, "Source", "GameData.cpp"), "w") as f:
    f.write("// GENERATED by tools/extract_assets.py from the original PureBasic data - do not edit.\n")
    f.write('#include "GameData.h"\n\nnamespace gamedata\n{\n')
    for n in ("palette", "sprites", "chars", "charColors", "map", "anims"):
        f.write(carray(n, parts[n]) + "\n")
    f.write("}  // namespace gamedata\n")
print("wrote Source/GameData.cpp")

# ---- 3. MIDI -> audio -----------------------------------------------------------
SR = 22050
mid = parts["midi"]
fmt, ntr, div = struct.unpack(">HHH", mid[8:14])
pos, notes, tempo = 14, [], 500000          # (tick_on, tick_off, ch, key, vel, program)
tempos = [(0, 500000)]
for _ in range(ntr):
    ln = struct.unpack(">I", mid[pos + 4:pos + 8])[0]
    tr = mid[pos + 8:pos + 8 + ln]; pos += 8 + ln
    i = tick = 0; rs = 0; prog = {}; active = {}
    while i < len(tr):
        v = 0
        while True:
            b = tr[i]; i += 1; v = (v << 7) | (b & 0x7F)
            if not b & 0x80: break
        tick += v
        s = tr[i]
        if s < 0x80: s = rs
        else: i += 1
        if s == 0xFF:
            ty, l = tr[i], tr[i + 1]; i += 2
            if ty == 0x51: tempos.append((tick, int.from_bytes(tr[i:i + 3], "big")))
            i += l
        elif s in (0xF0, 0xF7):
            l = tr[i]; i += 1 + l
        else:
            rs = s; hi, ch = s >> 4, s & 15
            if hi == 0xC: prog[ch] = tr[i]; i += 1
            elif hi == 0xD: i += 1
            else:
                a, b2 = tr[i], tr[i + 1]; i += 2
                if hi == 9 and b2 > 0: active[(ch, a)] = (tick, b2)
                elif hi == 8 or (hi == 9 and b2 == 0):
                    if (ch, a) in active:
                        t0, vel = active.pop((ch, a))
                        notes.append((t0, tick, ch, a, vel, prog.get(ch, 0)))
tempos.sort()
def ticks_to_sec(t):
    s, last_t, last_us = 0.0, 0, 500000
    for tt, us in tempos:
        if tt >= t: break
        s += (tt - last_t) * last_us / div / 1e6; last_t, last_us = tt, us
    return s + (t - last_t) * last_us / div / 1e6

end = max(ticks_to_sec(n[1]) for n in notes) + 2.0
buf = np.zeros(int(end * SR) + SR, dtype=np.float32)
for t0, t1, ch, key, vel, prog in notes:
    st, dur = ticks_to_sec(t0), ticks_to_sec(t1) - ticks_to_sec(t0)
    f = 440.0 * 2 ** ((key - 69) / 12.0)
    if prog in (10, 11, 14):        # music box / vibraphone / tubular bells: struck, decaying
        L = min(max(dur, 0.2) + 0.9, 3.0); decay = 3.0 if prog != 14 else 1.8
    else:                            # pan flute etc.: sustained, soft attack/release
        L = dur + 0.12; decay = 0.0
    n = int(L * SR); t = np.arange(n) / SR
    if prog in (10, 11):
        w = np.sin(2 * np.pi * f * t) + 0.35 * np.sin(2 * np.pi * f * 4 * t) * np.exp(-t * 8)
    elif prog == 14:
        w = np.sin(2 * np.pi * f * t) + 0.5 * np.sin(2 * np.pi * f * 2.76 * t) * np.exp(-t * 4)
    else:
        w = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(2 * np.pi * f * 2 * t) + 0.1 * np.sin(2 * np.pi * f * 3 * t)
    env = np.exp(-t * decay) if decay else np.ones(n)
    env = env * np.minimum(1.0, t / 0.01)
    if not decay: env = env * np.minimum(1.0, (L - t) / 0.12)
    a = int(st * SR)
    buf[a:a + n] += (w * env * (vel / 127.0) * 0.18).astype(np.float32)
buf = np.tanh(buf * 1.2)
pcm = (buf * 32767 * 0.9).astype("<i2")
wav = os.path.join(ROOT, "Content", "music.wav")
with wave.open(wav, "wb") as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())
try:
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", wav, "-c:a", "libvorbis", "-q:a", "3",
                    os.path.join(ROOT, "Content", "music.ogg")], check=True)
    os.remove(wav); print("wrote Content/music.ogg (%.0f s)" % (len(pcm) / SR))
except Exception as e:
    print("ffmpeg failed (%s) - kept Content/music.wav; change MUSIC_FILE in Source/GameScene.cpp" % e)
